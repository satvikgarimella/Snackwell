"""Shape-specialized Snackwell assembly and memory layouts for inference kernels.

The emitter generates instructions and immutable constants, never kernel results.
All tensor math, reductions, approximations, and masking execute on the SM.
"""

import math
from dataclasses import dataclass, field

from snackwell.numeric import SENTINEL, SHARED_WORDS, bits, value

NAMES = (
    "tiled_matmul",
    "bias_add",
    "residual_add",
    "relu",
    "gelu",
    "row_sum",
    "row_max",
    "layernorm",
    "softmax",
    "linear",
    "attention",
    "transformer",
)
SIZES = (4, 8, 16)


@dataclass
class Layout:
    """Shared-memory regions in words, with byte addresses for assembly operands."""

    memory: list[int] = field(default_factory=lambda: [SENTINEL] * SHARED_WORDS)
    regions: dict[str, tuple[int, int]] = field(default_factory=dict)
    constants: dict[int, int] = field(default_factory=dict)
    cursor: int = 0

    def allocate(self, name, count, data=None):
        if name in self.regions:
            raise ValueError(f"duplicate region {name}")
        start = (self.cursor + 3) & ~3
        if start + count > SHARED_WORDS:
            raise ValueError("workload exceeds the current 4 KB shared memory; use a smaller shape")
        if data is not None:
            if len(data) != count:
                raise ValueError(f"{name} requires exactly {count} elements")
            self.memory[start : start + count] = data
        self.regions[name] = (start, count)
        self.cursor = start + count
        return start * 4

    def address(self, name):
        return self.regions[name][0] * 4

    def constant(self, word):
        if word not in self.constants:
            if self.cursor >= SHARED_WORDS:
                raise ValueError("workload and constants exceed 4 KB shared memory")
            self.constants[word] = self.cursor * 4
            self.memory[self.cursor] = word
            self.cursor += 1
        return self.constants[word]


class Assembly:
    def __init__(self, layout, title):
        self.layout = layout
        self.lines = [
            f"; {title}",
            "; Generated by snackwell/kernels/inference.py. Launch warp 0, mask 0xf.",
            "; All addresses are bytes; R15 is explicitly initialized to zero.",
        ]

    def emit(self, text):
        self.lines.extend(line.strip() for line in text.strip().splitlines())

    def const(self, rd, number=None, word=None):
        address = self.layout.constant(bits(number) if word is None else word)
        self.emit(f"LD_SHARED R{rd}, [R15 + {address}]")

    def scale_index(self, rd, multiplier):
        if multiplier < 1 or multiplier & (multiplier - 1):
            raise ValueError("index stride must be a power of two")
        for _ in range(multiplier.bit_length() - 1):
            self.emit(f"ADD R{rd}, R{rd}, R{rd}")

    def text(self):
        return "\n".join(self.lines) + "\n"


def select(a, dst, false_reg, true_reg, predicate, tmp):
    """Select raw bits using a 0/1 predicate. Does not branch or alter lane masks."""
    a.emit(f"""SUB R{predicate}, R15, R{predicate}
        XOR R{tmp}, R{false_reg}, R{true_reg}
        AND R{tmp}, R{tmp}, R{predicate}
        XOR R{dst}, R{false_reg}, R{tmp}""")


def maximum(a, dst, left, right, predicate, tmp):
    a.emit(f"FLT R{predicate}, R{left}, R{right}")
    select(a, dst, left, right, predicate, tmp)


def reciprocal(a, src, dst, t, coefficient):
    """Positive normal input; four residual-form Newton refinements.

    y += y*(1-x*y) avoids losing the correction when (2-x*y) rounds to 1.
    """
    a.const(coefficient, word=0x7EF311C3)
    a.emit(f"SUB R{dst}, R{coefficient}, R{src}")
    a.const(coefficient, 1)
    for _ in range(4):
        a.emit(f"""FMUL R{t}, R{src}, R{dst}
            FSUB R{t}, R{coefficient}, R{t}
            FMUL R{t}, R{dst}, R{t}
            FADD R{dst}, R{dst}, R{t}""")


def rsqrt(a, src, dst, half_x, t, coefficient):
    """Positive normal input; four Newton iterations y *= 1.5 - 0.5*x*y*y."""
    a.emit(f"ADDI R{t}, R15, 1\nSHR R{t}, R{src}, R{t}")
    a.const(coefficient, word=0x5F3759DF)
    a.emit(f"SUB R{dst}, R{coefficient}, R{t}")
    a.const(coefficient, 0.5)
    a.emit(f"FMUL R{half_x}, R{src}, R{coefficient}")
    a.const(coefficient, 1.5)
    for _ in range(4):
        a.emit(f"""FMUL R{t}, R{dst}, R{dst}
            FMUL R{t}, R{half_x}, R{t}
            FSUB R{t}, R{coefficient}, R{t}
            FMUL R{dst}, R{dst}, R{t}""")


def exp_negative(a, src, dst, scaled, coefficient, mask, tmp):
    """exp(x) for x<=0. Values below -80 become zero; -inf is supported.

    Evaluate degree-six exp(x/32) by Horner, then square five times.
    Fewer squarings reduce amplified FP32 rounding near zero. Polynomial error
    grows in the far negative tail, where the absolute exponential is tiny.
    src is clamped in place. Caller supplies six distinct registers.
    """
    a.const(coefficient, -80)
    a.emit(f"FLT R{mask}, R{src}, R{coefficient}")
    select(a, src, src, coefficient, mask, tmp)
    a.const(coefficient, 1 / 32)
    a.emit(f"FMUL R{scaled}, R{src}, R{coefficient}")
    a.const(dst, 1 / 720)
    for c in (1 / 120, 1 / 24, 1 / 6, 0.5, 1, 1):
        a.const(coefficient, c)
        a.emit(f"FMUL R{dst}, R{dst}, R{scaled}\nFADD R{dst}, R{dst}, R{coefficient}")
    for _ in range(5):
        a.emit(f"FMUL R{dst}, R{dst}, R{dst}")
    a.emit(f"AND R{tmp}, R{dst}, R{mask}\nXOR R{dst}, R{dst}, R{tmp}")


def row_start(a, rows, cols, input_address, output_address, reduced=False):
    if rows == 1:
        # Preserve the scalar reduction order of one row. Usually only lane
        # zero is active; parallel-affine LayerNorm repeats these reads in all
        # lanes before distributing its independent output columns.
        a.emit(f"""XOR R15, R15, R15
            ADDI R12, R15, {input_address}
            ADDI R13, R15, {output_address}
            ADDI R14, R15, 1
            row_group:""")
        return
    # One lane owns a whole row; four lanes process four independent rows.
    a.emit("XOR R15, R15, R15\nTID R12")
    a.scale_index(12, cols * 4)
    a.emit(f"ADDI R12, R12, {input_address}\nTID R13")
    a.scale_index(13, 4 if reduced else cols * 4)
    a.emit(f"ADDI R13, R13, {output_address}\nADDI R14, R15, {rows // 4}\nrow_group:")


def row_end(a, cols, reduced=False):
    # A 512-column row-group stride is 8192 bytes, beyond signed 14-bit ADDI.
    for register, stride in ((12, cols * 16), (13, 16 if reduced else cols * 16)):
        while stride:
            increment = min(stride, 4096)
            a.emit(f"ADDI R{register}, R{register}, {increment}")
            stride -= increment
    a.emit("""ADDI R14, R14, -1
        BEQ R14, R15, done
        BEQ R15, R15, row_group
        done: EXIT""")


def elementwise(layout, kind, rows, cols, x="x", y="out", other="b", *, parallel_columns=False):
    a = Assembly(layout, f"{kind}: {rows} rows x {cols} columns")
    if rows == 1 and parallel_columns and kind in ("bias_add", "residual_add"):
        a.emit("XOR R15, R15, R15\nTID R12")
        a.scale_index(12, 4)
        for column in range(0, cols, 4):
            a.emit(f"""LD_SHARED R0, [R12 + {layout.address(x) + column * 4}]
                LD_SHARED R1, [R12 + {layout.address(other) + column * 4}]
                FADD R0, R0, R1
                ST_SHARED [R12 + {layout.address(y) + column * 4}], R0""")
        a.emit("EXIT")
        return a.text()
    # GELU's longer math sequence is reused by a counted loop over vector
    # groups, keeping even the 16x16 workload inside the 1024-word ROM.
    loop_rows, loop_cols = (rows * cols, 1) if kind == "gelu" else (rows, cols)
    row_start(a, loop_rows, loop_cols, layout.address(x), layout.address(y))
    for c in range(loop_cols):
        a.emit(f"LD_SHARED R0, [R12 + {c * 4}]")
        if kind in ("bias_add", "residual_add"):
            address = layout.address(other)
            base, offset = (
                (15, address + c * 4)
                if kind == "bias_add"
                else (12, address - layout.address(x) + c * 4)
            )
            sign = "+" if offset >= 0 else "-"
            a.emit(f"LD_SHARED R1, [R{base} {sign} {abs(offset)}]\nFADD R0, R0, R1")
        elif kind == "relu":
            maximum(a, 0, 0, 15, 1, 2)
        elif kind == "gelu":
            # Stable tanh-GELU expressed using exp(-2*abs(u)); x is kept in R0.
            a.const(1, word=0x7FFFFFFF)
            a.emit("AND R1, R0, R1")
            a.const(2, 10)
            a.emit("FLT R3, R2, R1")
            select(a, 1, 1, 2, 3, 4)
            a.emit("FMUL R2, R1, R1")
            a.const(3, 0.044715)
            a.emit("FMUL R2, R2, R3")
            a.const(3, 1)
            a.emit("FADD R2, R2, R3\nFMUL R2, R2, R1")
            a.const(3, -2 * math.sqrt(2 / math.pi))
            a.emit("FMUL R2, R2, R3")
            exp_negative(a, 2, 3, 4, 5, 6, 7)
            a.const(4, 1)
            a.emit("FADD R4, R4, R3")
            reciprocal(a, 4, 5, 6, 7)
            a.emit("FMUL R1, R0, R5\nFMUL R2, R1, R3\nFLT R3, R0, R15")
            select(a, 0, 1, 2, 3, 4)
        else:
            raise ValueError(kind)
        a.emit(f"ST_SHARED [R13 + {c * 4}], R0")
    row_end(a, loop_cols)
    return a.text()


def reduction(layout, kind, rows, cols, x="x", y="out"):
    a = Assembly(layout, f"{kind}: reduce {cols} columns in each of {rows} rows")
    row_start(a, rows, cols, layout.address(x), layout.address(y), reduced=True)
    a.emit("XOR R0, R0, R0" if kind == "row_sum" else "LD_SHARED R0, [R12]")
    for c in range(0 if kind == "row_sum" else 1, cols):
        a.emit(f"LD_SHARED R1, [R12 + {c * 4}]")
        if kind == "row_sum":
            a.emit("FADD R0, R0, R1")
        else:
            maximum(a, 0, 0, 1, 2, 3)
    a.emit("ST_SHARED [R13], R0")
    row_end(a, cols, reduced=True)
    return a.text()


def softmax(layout, rows, cols, x="x", y="out"):
    a = Assembly(layout, f"stable row softmax: {rows} x {cols}")
    row_start(a, rows, cols, layout.address(x), layout.address(y))
    a.emit("LD_SHARED R0, [R12]")
    for c in range(1, cols):
        a.emit(f"LD_SHARED R1, [R12 + {c * 4}]")
        maximum(a, 0, 0, 1, 2, 3)
    a.emit("XOR R1, R1, R1")
    for c in range(cols):
        a.emit(f"LD_SHARED R2, [R12 + {c * 4}]\nFSUB R2, R2, R0")
        exp_negative(a, 2, 3, 4, 5, 6, 7)
        a.emit(f"ST_SHARED [R13 + {c * 4}], R3\nFADD R1, R1, R3")
    reciprocal(a, 1, 2, 3, 4)
    for c in range(cols):
        a.emit(f"LD_SHARED R3, [R13 + {c * 4}]\nFMUL R3, R3, R2\nST_SHARED [R13 + {c * 4}], R3")
    row_end(a, cols)
    return a.text()


def layernorm(
    layout,
    rows,
    cols,
    epsilon,
    x="x",
    y="out",
    gamma="gamma",
    beta="beta",
    *,
    parallel_affine=False,
):
    if cols > 64:
        return loop_layernorm(
            layout, rows, cols, epsilon, x, y, gamma, beta, parallel_affine=parallel_affine
        )
    a = Assembly(layout, f"two-pass LayerNorm with affine gamma/beta: {rows} x {cols}")
    row_start(a, rows, cols, layout.address(x), layout.address(y))
    a.emit("XOR R0, R0, R0")
    for c in range(cols):
        a.emit(f"LD_SHARED R1, [R12 + {c * 4}]\nFADD R0, R0, R1")
    a.const(2, 1 / cols)
    a.emit("FMUL R0, R0, R2\nXOR R1, R1, R1")
    for c in range(cols):
        a.emit(f"""LD_SHARED R3, [R12 + {c * 4}]
            FSUB R3, R3, R0
            FMUL R3, R3, R3
            FADD R1, R1, R3""")
    a.emit("FMUL R1, R1, R2")
    a.const(2, epsilon)
    a.emit("FADD R1, R1, R2")
    rsqrt(a, 1, 2, 3, 4, 5)
    if rows == 1 and parallel_affine:
        layernorm_affine_lanes(a, cols, gamma, beta)
        return a.text()
    for c in range(cols):
        a.emit(f"""LD_SHARED R3, [R12 + {c * 4}]
            FSUB R3, R3, R0
            FMUL R3, R3, R2
            LD_SHARED R4, [R15 + {layout.address(gamma) + c * 4}]
            FMUL R3, R3, R4
            LD_SHARED R4, [R15 + {layout.address(beta) + c * 4}]
            FADD R3, R3, R4
            ST_SHARED [R13 + {c * 4}], R3""")
    row_end(a, cols)
    return a.text()


def layernorm_affine_lanes(a, cols, gamma, beta):
    """Share reduction inputs, then let each lane normalize distinct columns.

    Mean and variance are computed identically in each lane, in the original
    sequential order. Only the independent affine outputs are distributed.
    R0 holds the mean, R2 the inverse standard deviation, R12/R13 the row bases.
    """
    a.emit("TID R8")
    a.scale_index(8, 4)
    a.emit("ADD R12, R12, R8\nADD R13, R13, R8")
    for column in range(0, cols, 4):
        a.emit(f"""LD_SHARED R3, [R12 + {column * 4}]
            FSUB R3, R3, R0
            FMUL R3, R3, R2
            LD_SHARED R4, [R8 + {a.layout.address(gamma) + column * 4}]
            FMUL R3, R3, R4
            LD_SHARED R4, [R8 + {a.layout.address(beta) + column * 4}]
            FADD R3, R3, R4
            ST_SHARED [R13 + {column * 4}], R3""")
    a.emit("EXIT")


def loop_layernorm(
    layout,
    rows,
    cols,
    epsilon,
    x="x",
    y="out",
    gamma="gamma",
    beta="beta",
    *,
    parallel_affine=False,
):
    """Keep wide LayerNorm inside ROM without changing its FP32 reduction order."""
    a = Assembly(layout, f"two-pass looped LayerNorm: {rows} x {cols}")
    row_start(a, rows, cols, layout.address(x), layout.address(y))
    a.emit(f"""XOR R0, R0, R0
        ADD R8, R12, R15
        ADDI R9, R15, {cols}
        mean_loop:
        LD_SHARED R1, [R8]
        FADD R0, R0, R1
        ADDI R8, R8, 4
        ADDI R9, R9, -1
        BEQ R9, R15, mean_done
        BEQ R15, R15, mean_loop
        mean_done:""")
    a.const(2, 1 / cols)
    a.emit(f"""FMUL R0, R0, R2
        XOR R1, R1, R1
        ADD R8, R12, R15
        ADDI R9, R15, {cols}
        variance_loop:
        LD_SHARED R3, [R8]
        FSUB R3, R3, R0
        FMUL R3, R3, R3
        FADD R1, R1, R3
        ADDI R8, R8, 4
        ADDI R9, R9, -1
        BEQ R9, R15, variance_done
        BEQ R15, R15, variance_loop
        variance_done:
        FMUL R1, R1, R2""")
    a.const(2, epsilon)
    a.emit("FADD R1, R1, R2")
    rsqrt(a, 1, 2, 3, 4, 5)
    if rows == 1 and parallel_affine:
        layernorm_affine_lanes(a, cols, gamma, beta)
        return a.text()
    a.emit(f"""XOR R8, R8, R8
        ADDI R9, R15, {cols}
        affine_loop:
        ADD R10, R12, R8
        ADD R11, R13, R8
        LD_SHARED R3, [R10]
        FSUB R3, R3, R0
        FMUL R3, R3, R2
        LD_SHARED R4, [R8 + {layout.address(gamma)}]
        FMUL R3, R3, R4
        LD_SHARED R4, [R8 + {layout.address(beta)}]
        FADD R3, R3, R4
        ST_SHARED [R11], R3
        ADDI R8, R8, 4
        ADDI R9, R9, -1
        BEQ R9, R15, affine_done
        BEQ R15, R15, affine_loop
        affine_done:""")
    row_end(a, cols)
    return a.text()


def tiled_matmul(
    layout,
    m,
    n,
    k,
    left="a",
    right="b",
    out="out",
    transpose_b=False,
    accumulate=False,
    warps=1,
    bias=None,
):
    if m != 1 and (m < 4 or m % 4):
        raise ValueError("matmul rows must be one or a multiple of four")
    tile_rows = min(m, 4)
    a = Assembly(layout, f"tiled FP32 matmul {m}x{k} @ {k}x{n}; B transposed={transpose_b}")
    tiles = [(row, col) for row in range(0, m, 4) for col in range(0, n, 4)]
    if type(warps) is not int or not 1 <= warps <= min(4, len(tiles)):
        raise ValueError("matmul requires 1..4 warps and at least one output tile per warp")
    if warps > 1:
        a.lines[1] = f"; Launch warps 0..{warps - 1}, each with four active lanes."
        # All lanes in a warp take the same branch. Output tiles are disjoint;
        # each warp keeps the original K reduction order in its own registers.
        a.emit("XOR R15, R15, R15\nTID R0\nADDI R1, R15, 2\nSHR R0, R0, R1")
        for warp in range(warps):
            a.emit(f"ADDI R1, R15, {warp}\nBEQ R0, R1, warp_{warp}")
        a.emit("EXIT")
    # R8..R11 retain C through the K loop. TMUL gathers A before replacing
    # R0..R3 with its result, so only the completed tile goes back to memory.
    for warp in range(warps):
        if warps > 1:
            a.emit(f"warp_{warp}:")
        for row, col in tiles[warp::warps]:
            label = f"tile_{row}_{col}"
            a.emit("TID R12")
            if warp:
                a.emit(f"ADDI R12, R12, {-4 * warp}")
            a.scale_index(12, 4)
            a.emit(f"ADDI R14, R12, {layout.address(out) + (row * n + col) * 4}")
            if transpose_b:
                a.emit("TID R13")
                if warp:
                    a.emit(f"ADDI R13, R13, {-4 * warp}")
                a.scale_index(13, k * 4)
                a.emit(f"ADDI R13, R13, {layout.address(right) + col * k * 4}")
            else:
                a.emit(f"ADDI R13, R12, {layout.address(right) + col * 4}")
            a.emit(f"ADDI R12, R12, {layout.address(left) + row * k * 4}\nXOR R15, R15, R15")
            for r in range(tile_rows):
                a.emit(
                    f"LD_SHARED R{r + 8}, [R14 + {r * n * 4}]"
                    if accumulate
                    else f"XOR R{r + 8}, R{r + 8}, R{r + 8}"
                )
            a.emit(f"ADDI R15, R15, {k // 4}\n{label}:")
            for r in range(4):
                a.emit(
                    f"LD_SHARED R{r}, [R12 + {r * k * 4}]"
                    if r < tile_rows
                    else f"XOR R{r}, R{r}, R{r}"
                )
                a.emit(f"LD_SHARED R{r + 4}, [R13 + {r * 4 if transpose_b else r * n * 4}]")
            a.emit("TMUL R0, R0, R4")
            for r in range(tile_rows):
                a.emit(f"FADD R{r + 8}, R{r + 8}, R{r}")
            a.emit(f"""ADDI R12, R12, 16
                ADDI R13, R13, {16 if transpose_b else 16 * n}
                ADDI R15, R15, -1
                XOR R0, R0, R0
                BEQ R15, R0, {label}_done
                BEQ R0, R0, {label}
                {label}_done:""")
            if bias is not None:
                offset = layout.address(bias) - layout.address(out) - row * n * 4
                a.emit(f"LD_SHARED R0, [R14 {offset:+d}]")
                for r in range(tile_rows):
                    a.emit(f"FADD R{r + 8}, R{r + 8}, R0")
            for r in range(tile_rows):
                a.emit(f"ST_SHARED [R14 + {r * n * 4}], R{r + 8}")
        a.emit("EXIT")
    return a.text()


def scale_mask(layout, rows, width, causal, x="scores", columns=None, row_offset=0):
    columns = rows if columns is None else columns
    a = Assembly(layout, f"attention scale by 1/sqrt({width}), causal={causal}")
    row_start(a, rows, columns, layout.address(x), layout.address(x))
    # R11 is the query row. Set it before the loop label so it advances by 4.
    a.lines.insert(a.lines.index("row_group:"), "XOR R11, R11, R11" if rows == 1 else "TID R11")
    if row_offset:
        a.lines.insert(a.lines.index("row_group:"), f"ADDI R11, R11, {row_offset}")
    a.const(8, 1 / math.sqrt(width))
    a.const(9, word=0xFF800000)
    if columns > 64:
        a.emit(f"""XOR R3, R3, R3
            ADD R4, R12, R15
            ADDI R5, R15, {columns}
            mask_column:
            LD_SHARED R0, [R4]
            FMUL R0, R0, R8""")
        if causal:
            a.emit("SLTU R1, R11, R3")
            select(a, 0, 0, 9, 1, 2)
        a.emit("""ST_SHARED [R4], R0
            ADDI R3, R3, 1
            ADDI R4, R4, 4
            BEQ R3, R5, mask_done
            BEQ R15, R15, mask_column
            mask_done:
            ADDI R11, R11, 4""")
        row_end(a, columns)
        return a.text()
    for c in range(columns):
        a.emit(f"LD_SHARED R0, [R12 + {c * 4}]\nFMUL R0, R0, R8")
        if causal:
            a.emit(f"ADDI R1, R15, {c}\nSLTU R1, R11, R1")
            select(a, 0, 0, 9, 1, 2)
        a.emit(f"ST_SHARED [R13 + {c * 4}], R0")
    a.emit("ADDI R11, R11, 4")
    row_end(a, columns)
    return a.text()


@dataclass
class Stage:
    name: str
    source: str
    operation: str
    inputs: tuple[str, ...]
    output: str
    params: dict[str, int | float | bool]


@dataclass
class Case:
    name: str
    layout: Layout
    stages: list[Stage]
    rows: int
    cols: int


def build_case(name, rows=4, cols=4, size=8, inputs=None):
    if name not in NAMES or rows not in SIZES or cols not in SIZES or size not in SIZES:
        raise ValueError("supported dimensions are 4, 8, and 16")
    inputs = {} if inputs is None else inputs
    if not isinstance(inputs, dict):
        raise ValueError("inputs must be a JSON object")
    if name == "transformer":
        from snackwell.kernels.transformer import build_transformer

        return build_transformer(rows, cols, inputs)
    allowed = {
        "linear": {"a", "b", "bias"},
        "tiled_matmul": {"a", "b"},
        "attention": {"q", "k", "v", "causal"},
        "layernorm": {"x", "gamma", "beta", "epsilon"},
        "bias_add": {"x", "b"},
        "residual_add": {"x", "b"},
    }.get(name, {"x"})
    if set(inputs) - allowed:
        raise ValueError(
            f"unexpected input keys: {sorted(set(inputs) - allowed)}; expected {sorted(allowed)}"
        )
    layout, stages = Layout(), []
    if name in ("tiled_matmul", "linear"):
        rows = cols = size

    def data(key, count, default, allow_negative_inf=False, allow_special=False):
        raw = inputs.get(key, default)
        if not isinstance(raw, list) or len(raw) != count:
            raise ValueError(f"{key} requires exactly {count} values")
        result = [bits(x) for x in raw]
        for word in result:
            x = value(word)
            if (
                not allow_special
                and not math.isfinite(x)
                and not (allow_negative_inf and x == -math.inf)
            ):
                raise ValueError(f"{key} requires finite FP32 inputs")
        layout.allocate(key, count, result)

    def add(stage_name, source, op, ins, output="out", **params):
        stages.append(Stage(stage_name, source, op, tuple(ins), output, params))

    if name in ("tiled_matmul", "linear"):
        data("a", size * size, [(i % 13 - 6) / 8 for i in range(size * size)])
        data("b", size * size, [(i % 11 - 5) / 4 for i in range(size * size)])
        layout.allocate("out", size * size)
        if name == "linear":
            data("bias", size, [(i - 2) / 8 for i in range(size)])
        add(
            "matmul",
            tiled_matmul(layout, size, size, size),
            "matmul",
            ("a", "b"),
            m=size,
            n=size,
            k=size,
        )
        if name == "linear":
            add(
                "bias",
                elementwise(layout, "bias_add", size, size, "out", "out", "bias"),
                "bias_add",
                ("out", "bias"),
                rows=size,
                cols=size,
            )
    elif name == "attention":
        data("q", rows * cols, [(i % 11 - 5) / 8 for i in range(rows * cols)])
        data("k", rows * cols, [(i % 7 - 3) / 4 for i in range(rows * cols)])
        data("v", rows * cols, [(i % 13 - 6) / 4 for i in range(rows * cols)])
        layout.allocate("scores", rows * rows)
        layout.allocate("out", rows * cols)
        causal = inputs.get("causal", True)
        if type(causal) is not bool:
            raise ValueError("causal must be true or false")
        add(
            "qk",
            tiled_matmul(layout, rows, rows, cols, "q", "k", "scores", True),
            "matmul",
            ("q", "k"),
            "scores",
            m=rows,
            n=rows,
            k=cols,
            transpose_b=True,
        )
        add(
            "scale_mask",
            scale_mask(layout, rows, cols, causal),
            "scale_mask",
            ("scores",),
            "scores",
            rows=rows,
            cols=rows,
            width=cols,
            causal=causal,
        )
        add(
            "softmax",
            softmax(layout, rows, rows, "scores", "scores"),
            "softmax",
            ("scores",),
            "scores",
            rows=rows,
            cols=rows,
        )
        add(
            "pv",
            tiled_matmul(layout, rows, cols, rows, "scores", "v"),
            "matmul",
            ("scores", "v"),
            m=rows,
            n=cols,
            k=rows,
        )
    else:
        data(
            "x",
            rows * cols,
            [(i % 17 - 8) / 4 for i in range(rows * cols)],
            allow_negative_inf=name == "softmax",
            allow_special=name == "relu",
        )
        if name in ("bias_add", "residual_add"):
            count = cols if name == "bias_add" else rows * cols
            data("b", count, [(i % 5 - 2) / 8 for i in range(count)])
        if name == "layernorm":
            data("gamma", cols, [1] * cols)
            data("beta", cols, [0] * cols)
        layout.allocate("out", rows if name in ("row_sum", "row_max") else rows * cols)
        if name in ("bias_add", "residual_add", "relu", "gelu"):
            ins = ("x", "b") if name in ("bias_add", "residual_add") else ("x",)
            add(name, elementwise(layout, name, rows, cols), name, ins, rows=rows, cols=cols)
        elif name in ("row_sum", "row_max"):
            add(name, reduction(layout, name, rows, cols), name, ("x",), rows=rows, cols=cols)
        elif name == "softmax":
            start, _ = layout.regions["x"]
            for r in range(rows):
                if all(
                    value(w) == -math.inf
                    for w in layout.memory[start + r * cols : start + (r + 1) * cols]
                ):
                    raise ValueError("softmax requires at least one finite value in each row")
            add(name, softmax(layout, rows, cols), name, ("x",), rows=rows, cols=cols)
        elif name == "layernorm":
            epsilon = value(bits(inputs.get("epsilon", 1e-5)))
            if not math.isfinite(epsilon) or epsilon < value(0x00800000):
                raise ValueError("epsilon must be positive normal FP32")
            add(
                name,
                layernorm(layout, rows, cols, epsilon),
                name,
                ("x", "gamma", "beta"),
                rows=rows,
                cols=cols,
                epsilon=epsilon,
            )
    return Case(name, layout, stages, rows, cols)
